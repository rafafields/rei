import fs from 'node:fs';
import path from 'node:path';
import { retintTheme } from './palette.mjs';
import { fontToml } from './fonts.mjs';

export const baseThemeFile = (repo) => path.join(repo, 'theme', 'rei.toml');
export const generatedThemeFile = (repo) => path.join(repo, 'config', 'theme.toml');

/** Pure: the theme text with the user's colours and font. */
export function buildTheme(baseText, mapper, font) {
  const header = '# Generated by the Rei installer from theme/rei.toml. Run `rei -Customize` to change it.\n';
  return header + retintTheme(baseText, mapper) + fontToml(font ?? {});
}

export function writeTheme(repo, mapper, font) {
  const out = generatedThemeFile(repo);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, buildTheme(fs.readFileSync(baseThemeFile(repo), 'utf8'), mapper, font), 'utf8');
  return out;
}
